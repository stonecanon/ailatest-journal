function getLang() {
  return wx.getStorageSync('journalai.lang') || 'zh-CN'
}

function setLang(code) {
  const lang = DICT[code] ? code : 'zh-CN'
  wx.setStorageSync('journalai.lang', lang)
  return lang
}

function t(key, lang = getLang()) {
  return (DICT[lang] && DICT[lang][key]) || ZH[key] || key
}

function pageText(lang = getLang()) {
  return Object.keys(ZH).reduce((acc, key) => {
    acc[key] = t(key, lang)
    return acc
  }, {})
}

function languages(lang = getLang()) {
  return LANGS.map(item => ({ ...item, active: item.code === lang }))
}

module.exports = {
  LANGS,
  getLang,
  setLang,
  t,
  pageText,
  languages
}
